# Demonstrates basic set operations like add and remove
# 1. Create a set with duplicates
my_set = {1, 2, 2, 3, 4, 4, 5}

# 2. Print the set
print("Set:", my_set)

# 3. Add a new element
my_set.add(10)
print("After adding 10:", my_set)

# 4. Remove an element
my_set.remove(2)
print("After removing 2:", my_set)